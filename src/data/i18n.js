export function getStoredLanguage() {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE;
  const stored = window.localStorage.getItem('shiksha-language');
  return SUPPORTED_LANGUAGES.includes(stored) ? stored : DEFAULT_LANGUAGE;
}

export function setStoredLanguage(language) {
  if (typeof window === 'undefined') return;
  const selected = SUPPORTED_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
  window.localStorage.setItem('shiksha-language', selected);
}

export function getLanguageLabel(language) {
  return language === 'hi' ? 'हिन्दी' : 'English';
}
